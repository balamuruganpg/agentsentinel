#!/usr/bin/env python3
"""Generate the AgentSentinel README charts from the v0.3.0 eval report.

Source: evals/results/benchmark-v0.3.0.md
  Default-threshold table: precision, recall, F1, FPR, and TP/FP/TN/FN.
  Category table: v0.3.0 recall for exfiltration, destruction, and
  privilege escalation, including the published hit counts.

The README "Independent benchmark" tables are the published record. This
script checks that the v0.3.0 headline row and category recalls in README.md
match the report before it draws. Stdlib only. A second run writes the same
bytes.
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
ASSET_DIR = Path(__file__).resolve().parent
REPORT_PATH = ROOT / "evals" / "results" / "benchmark-v0.3.0.md"
README_PATH = ROOT / "README.md"

INK = "#1f1f1f"
MUTED = "#5c5c5c"
BAR = "#2f2f2f"
ACCENT = "#b42318"
TRACK = "#f2f2f2"
AXIS = "#c4c4c4"
HAIR = "#d0d0d0"
WHITE = "#ffffff"
TILE = "#f7f7f7"
FONT = "sans-serif"
SVG_NS = "http://www.w3.org/2000/svg"
RATE = r"(?:0\.[0-9]{4}|1\.0000)"
FOUR = Decimal("0.0001")
CENT = Decimal("0.01")

HEADLINE_ROW = re.compile(
    rf"^\| v0\.3\.0 \| ({RATE}) \| ({RATE}) \| ({RATE}) \| ({RATE}) \| "
    rf"(\d+) / (\d+) / (\d+) / (\d+) \|$",
    re.MULTILINE,
)
README_RECALL_ROW = re.compile(
    rf"^\| v0\.3\.0 \| ({RATE}) \| ({RATE}) \| ({RATE}) \|$",
    re.MULTILINE,
)
CATEGORY_ROW = re.compile(
    rf"^\| (Exfiltration|Destruction|Privilege escalation) \| (\d+) \| "
    rf"{RATE} \(\d+/\d+\) \| ({RATE}) \((\d+)/(\d+)\) \|$",
    re.MULTILINE,
)
CATEGORY_ORDER = ("Exfiltration", "Destruction", "Privilege escalation")


def xml_text(value: object) -> str:
    return escape(str(value), entities={'"': "&quot;", "'": "&apos;"})


def coord(value: Decimal | int) -> str:
    return f"{Decimal(value):.2f}"


def quantize(value: Decimal, places: Decimal) -> Decimal:
    return value.quantize(places, rounding=ROUND_HALF_UP)


def four_places(numerator: int, denominator: int) -> str:
    if denominator <= 0:
        raise SystemExit(f"denominator for {numerator} is not positive")
    return f"{quantize(Decimal(numerator) / Decimal(denominator), FOUR):.4f}"


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def require_one(pattern: re.Pattern[str], text: str, label: str) -> re.Match[str]:
    found = list(pattern.finditer(text))
    if len(found) != 1:
        raise SystemExit(f"{label}: expected 1 match, found {len(found)}")
    return found[0]


def parse_svg(text: str, label: str) -> None:
    try:
        root = ET.fromstring(text)
    except ET.ParseError as error:
        raise SystemExit(f"{label}: generated SVG is not valid XML: {error}") from error
    if root.tag != f"{{{SVG_NS}}}svg":
        raise SystemExit(f"{label}: root is {root.tag}, expected svg")


def _tag(indent: int, body: str) -> str:
    return f"{' ' * indent}{body}\n"


def text(
    x: Decimal | int,
    y: Decimal | int,
    content: str,
    size: int,
    fill: str,
    *,
    anchor: str = "start",
    weight: str = "400",
    indent: int = 2,
) -> str:
    return _tag(
        indent,
        f'<text x="{coord(x)}" y="{coord(y)}" text-anchor="{anchor}" '
        f'dominant-baseline="middle" font-family="{FONT}" font-size="{size}" '
        f'font-weight="{weight}" fill="{fill}">{xml_text(content)}</text>',
    )


def line(
    x1: Decimal | int,
    y1: Decimal | int,
    x2: Decimal | int,
    y2: Decimal | int,
    *,
    indent: int = 2,
) -> str:
    return _tag(
        indent,
        f'<line x1="{coord(x1)}" y1="{coord(y1)}" x2="{coord(x2)}" y2="{coord(y2)}" '
        f'stroke="{AXIS}" stroke-width="1"/>',
    )


def rect(
    x: Decimal | int,
    y: Decimal | int,
    width: Decimal | int,
    height: Decimal | int,
    fill: str,
    *,
    stroke: str | None = None,
    indent: int = 2,
) -> str:
    edge = f' stroke="{stroke}" stroke-width="1"' if stroke else ""
    return _tag(
        indent,
        f'<rect x="{coord(x)}" y="{coord(y)}" width="{coord(width)}" '
        f'height="{coord(height)}" fill="{fill}"{edge}/>',
    )


def group(tooltip: str, body: str) -> str:
    return (
        '  <g class="mark" tabindex="0">\n'
        f"    <title>{xml_text(tooltip)}</title>\n"
        f"{body}"
        "  </g>\n"
    )


def document(
    width: int,
    height: int,
    title_id: str,
    desc_id: str,
    title: str,
    desc: str,
    inner: str,
) -> str:
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Generated by docs/assets/make_charts.py from "
        "evals/results/benchmark-v0.3.0.md. -->\n"
        f'<svg xmlns="{SVG_NS}" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" '
        f'aria-labelledby="{title_id} {desc_id}">\n'
        f'  <title id="{title_id}">{xml_text(title)}</title>\n'
        f'  <desc id="{desc_id}">{xml_text(desc)}</desc>\n'
        "  <style>\n"
        "    .mark:focus { outline: 2px solid #1f1f1f; outline-offset: 2px; }\n"
        "  </style>\n"
        f'  <rect width="{width}" height="{height}" fill="{WHITE}"/>\n'
        f"{inner}</svg>\n"
    )


class Headline:
    def __init__(
        self,
        precision: str,
        recall: str,
        f1: str,
        fpr: str,
        tp: int,
        fp: int,
        tn: int,
        fn: int,
    ) -> None:
        self.precision = precision
        self.recall = recall
        self.f1 = f1
        self.fpr = fpr
        self.tp = tp
        self.fp = fp
        self.tn = tn
        self.fn = fn

    def rates(self) -> tuple[str, str, str, str]:
        return (self.precision, self.recall, self.f1, self.fpr)

    def counts(self) -> tuple[int, int, int, int]:
        return (self.tp, self.fp, self.tn, self.fn)


class Category:
    def __init__(self, name: str, support: int, recall: str, hits: int) -> None:
        self.name = name
        self.support = support
        self.recall = recall
        self.hits = hits


def check_headline(row: Headline, label: str) -> None:
    expected = (
        four_places(row.tp, row.tp + row.fp),
        four_places(row.tp, row.tp + row.fn),
        f"{quantize(f1_ratio(row.tp, row.fp, row.fn), FOUR):.4f}",
        four_places(row.fp, row.fp + row.tn),
    )
    if row.rates() != expected:
        raise SystemExit(f"{label}: published rates {row.rates()} != counts {expected}")
    if row.tp + row.fn != 40 or row.fp + row.tn != 80:
        raise SystemExit(
            f"{label}: confusion counts are not 40 malicious and 80 benign"
        )


def f1_ratio(tp: int, fp: int, fn: int) -> Decimal:
    precision = Decimal(tp) / Decimal(tp + fp)
    recall = Decimal(tp) / Decimal(tp + fn)
    return (Decimal(2) * precision * recall) / (precision + recall)


def parse_headline(text: str, label: str) -> Headline:
    match = require_one(HEADLINE_ROW, text, f"{label} v0.3.0 headline")
    precision, recall, f1, fpr, tp, fp, tn, fn = match.groups()
    row = Headline(precision, recall, f1, fpr, int(tp), int(fp), int(tn), int(fn))
    check_headline(row, label)
    return row


def parse_categories(report: str) -> list[Category]:
    found = list(CATEGORY_ROW.finditer(report))
    names = [match.group(1) for match in found]
    if names != list(CATEGORY_ORDER):
        raise SystemExit(f"report categories {names} != {list(CATEGORY_ORDER)}")
    rows: list[Category] = []
    for match in found:
        name, support_text, recall, hits_text, denominator_text = match.groups()
        support = int(support_text)
        hits = int(hits_text)
        denominator = int(denominator_text)
        if denominator != support:
            raise SystemExit(
                f"{name}: recall denominator {denominator} != support {support}"
            )
        expected = four_places(hits, support)
        if recall != expected:
            raise SystemExit(
                f"{name}: published recall {recall} != {hits}/{support} ({expected})"
            )
        rows.append(Category(name, support, recall, hits))
    support_total = sum(row.support for row in rows)
    if support_total != 40:
        raise SystemExit(f"category support sums to {support_total}, expected 40")
    return rows


def check_category_hits(categories: list[Category], headline: Headline) -> None:
    hit_total = sum(row.hits for row in categories)
    if hit_total != headline.tp:
        raise SystemExit(
            f"category hits sum to {hit_total}, "
            f"headline true positives are {headline.tp}"
        )


def parse_readme_recalls(readme: str) -> tuple[str, str, str]:
    match = require_one(README_RECALL_ROW, readme, "README v0.3.0 category recall")
    return match.group(1), match.group(2), match.group(3)


def load() -> tuple[Headline, list[Category]]:
    report = REPORT_PATH.read_text(encoding="utf-8")
    readme = README_PATH.read_text(encoding="utf-8")
    headline = parse_headline(report, "report")
    readme_headline = parse_headline(readme, "README")
    rates_match = headline.rates() == readme_headline.rates()
    counts_match = headline.counts() == readme_headline.counts()
    if not rates_match or not counts_match:
        raise SystemExit("README headline table does not match the v0.3.0 eval report")
    categories = parse_categories(report)
    check_category_hits(categories, headline)
    readme_recalls = parse_readme_recalls(readme)
    report_recalls = tuple(row.recall for row in categories)
    if readme_recalls != report_recalls:
        raise SystemExit(
            f"README category recalls {readme_recalls} != report {report_recalls}"
        )
    return headline, categories


def axis_block(
    axis_x: Decimal, axis_y: Decimal, plot_w: Decimal, label_y: Decimal
) -> str:
    parts = [line(axis_x, axis_y, axis_x + plot_w, axis_y)]
    for index, label in enumerate(("0", "0.25", "0.50", "0.75", "1")):
        x = axis_x + plot_w * Decimal(index) / Decimal(4)
        parts.append(line(x, axis_y, x, axis_y + Decimal(5)))
        parts.append(text(x, label_y, label, 11, MUTED, anchor="middle"))
    return "".join(parts)


def build_benchmark(headline: Headline, categories: list[Category]) -> str:
    width = 720
    tile_y = Decimal(72)
    tile_h = Decimal(84)
    tile_w = Decimal(159)
    tile_gap = Decimal(12)
    tile_x0 = Decimal(24)
    recalls = [Decimal(row.recall) for row in categories]
    lowest = min(recalls)
    accent_lowest = sum(rate == lowest for rate in recalls) == 1
    metrics = (
        (
            "Precision",
            headline.precision,
            "higher is better",
            f"Precision {headline.precision}. True positives {headline.tp}, "
            f"false positives {headline.fp}.",
        ),
        (
            "Recall",
            headline.recall,
            "higher is better",
            f"Recall {headline.recall}. True positives {headline.tp}, "
            f"false negatives {headline.fn}.",
        ),
        ("F1", headline.f1, "higher is better", f"F1 {headline.f1}."),
        (
            "FPR",
            headline.fpr,
            "lower is better",
            f"False-positive rate {headline.fpr}. False positives {headline.fp}, "
            f"true negatives {headline.tn}.",
        ),
    )
    parts = [
        text(24, 28, "Independent benchmark, v0.3.0", 18, INK, weight="600"),
        text(24, 50, "120 traces · threshold 0.5 · 40 malicious, 80 benign", 12, MUTED),
    ]
    for index, (name, rate, hint, tooltip) in enumerate(metrics):
        x = tile_x0 + Decimal(index) * (tile_w + tile_gap)
        parts.append(
            group(
                tooltip,
                rect(x, tile_y, tile_w, tile_h, TILE, stroke=HAIR, indent=4)
                + text(
                    x + tile_w / 2,
                    tile_y + Decimal(22),
                    name,
                    12,
                    MUTED,
                    anchor="middle",
                    indent=4,
                )
                + text(
                    x + tile_w / 2,
                    tile_y + Decimal(46),
                    rate,
                    20,
                    INK,
                    anchor="middle",
                    weight="600",
                    indent=4,
                )
                + text(
                    x + tile_w / 2,
                    tile_y + Decimal(66),
                    hint,
                    11,
                    MUTED,
                    anchor="middle",
                    indent=4,
                ),
            )
        )

    label_right = Decimal(176)
    axis_x = Decimal(188)
    plot_w = Decimal(508)
    row_h = Decimal(40)
    bar_h = Decimal(20)
    first_center = Decimal(214)
    parts.append(text(24, 182, "Category recall", 14, INK, weight="600"))
    for index, row in enumerate(categories):
        center = first_center + Decimal(index) * row_h
        rate = Decimal(row.recall)
        bar_w = quantize(rate * plot_w, CENT)
        fill = ACCENT if accent_lowest and rate == lowest else BAR
        if bar_w >= 72:
            label_x = axis_x + bar_w - Decimal(8)
            label_fill = WHITE
            anchor = "end"
        else:
            label_x = axis_x + bar_w + Decimal(8)
            label_fill = INK
            anchor = "start"
        tooltip = f"{row.name} recall {row.recall} ({row.hits} of {row.support})"
        parts.append(
            group(
                tooltip,
                rect(axis_x, center - bar_h / 2, plot_w, bar_h, TRACK, indent=4)
                + rect(axis_x, center - bar_h / 2, bar_w, bar_h, fill, indent=4)
                + text(label_right, center, row.name, 13, INK, anchor="end", indent=4)
                + text(
                    label_x,
                    center,
                    row.recall,
                    12,
                    label_fill,
                    anchor=anchor,
                    weight="600",
                    indent=4,
                ),
            )
        )

    last_center = first_center + Decimal(len(categories) - 1) * row_h
    axis_y = last_center + bar_h / 2 + Decimal(16)
    parts.append(axis_block(axis_x, axis_y, plot_w, axis_y + Decimal(16)))
    note_y = axis_y + Decimal(40)
    source_y = note_y + Decimal(18)
    parts.append(text(24, note_y, "Red marks the lowest category recall.", 12, MUTED))
    parts.append(text(24, source_y, f"Source: {rel(REPORT_PATH)}", 12, MUTED))
    height = int(source_y + Decimal(24))
    desc = (
        "v0.3.0 at threshold 0.5. "
        f"Precision {headline.precision}, recall {headline.recall}, "
        f"F1 {headline.f1}, FPR {headline.fpr}. "
        + "; ".join(
            f"{row.name} recall {row.recall} ({row.hits} of {row.support})"
            for row in categories
        )
        + "."
    )
    return document(
        width,
        height,
        "benchmark-title",
        "benchmark-desc",
        "Independent benchmark, v0.3.0",
        desc,
        "".join(parts),
    )


def build_confusion(headline: Headline) -> str:
    width = 640
    origin_x = Decimal(168)
    origin_y = Decimal(108)
    cell_w = Decimal(210)
    cell_h = Decimal(112)
    gap = Decimal(12)
    cells = (
        (
            0,
            0,
            str(headline.tp),
            "True positive",
            TILE,
            HAIR,
            INK,
            f"True positive: {headline.tp}",
        ),
        (
            1,
            0,
            str(headline.fn),
            "False negative",
            ACCENT,
            ACCENT,
            WHITE,
            f"False negative: {headline.fn}",
        ),
        (
            0,
            1,
            str(headline.fp),
            "False positive",
            TILE,
            HAIR,
            INK,
            f"False positive: {headline.fp}",
        ),
        (
            1,
            1,
            str(headline.tn),
            "True negative",
            TILE,
            HAIR,
            INK,
            f"True negative: {headline.tn}",
        ),
    )
    parts = [
        text(24, 28, "Confusion counts, v0.3.0", 18, INK, weight="600"),
        text(24, 50, "Threshold 0.5 · 120 traces", 12, MUTED),
        text(24, 78, "Actual", 12, MUTED),
        text(
            origin_x + cell_w / 2,
            78,
            "Predicted flagged",
            12,
            MUTED,
            anchor="middle",
        ),
        text(
            origin_x + cell_w + gap + cell_w / 2,
            78,
            "Predicted clear",
            12,
            MUTED,
            anchor="middle",
        ),
    ]
    labels = {0: "Malicious", 1: "Benign"}
    for column, row, count, name, fill, stroke, ink, tooltip in cells:
        x = origin_x + Decimal(column) * (cell_w + gap)
        y = origin_y + Decimal(row) * (cell_h + gap)
        parts.append(
            group(
                tooltip,
                rect(x, y, cell_w, cell_h, fill, stroke=stroke, indent=4)
                + text(
                    x + cell_w / 2,
                    y + Decimal(46),
                    count,
                    32,
                    ink,
                    anchor="middle",
                    weight="600",
                    indent=4,
                )
                + text(
                    x + cell_w / 2,
                    y + Decimal(78),
                    name,
                    13,
                    ink,
                    anchor="middle",
                    indent=4,
                ),
            )
        )
    for row, label in labels.items():
        center = origin_y + Decimal(row) * (cell_h + gap) + cell_h / 2
        parts.append(text(origin_x - Decimal(12), center, label, 13, INK, anchor="end"))
    grid_bottom = origin_y + cell_h * 2 + gap
    note_y = grid_bottom + Decimal(28)
    source_y = note_y + Decimal(18)
    parts.append(
        text(
            24,
            note_y,
            "Red cell: false negatives, the malicious traces still missed.",
            12,
            MUTED,
        )
    )
    parts.append(text(24, source_y, f"Source: {rel(REPORT_PATH)}", 12, MUTED))
    height = int(source_y + Decimal(24))
    desc = (
        "Confusion counts at threshold 0.5: "
        f"true positives {headline.tp}, false positives {headline.fp}, "
        f"true negatives {headline.tn}, false negatives {headline.fn}."
    )
    return document(
        width,
        height,
        "confusion-title",
        "confusion-desc",
        "Confusion counts, v0.3.0",
        desc,
        "".join(parts),
    )


def main() -> None:
    headline, categories = load()
    benchmark_svg = build_benchmark(headline, categories)
    confusion_svg = build_confusion(headline)
    parse_svg(benchmark_svg, "benchmark.svg")
    parse_svg(confusion_svg, "confusion.svg")
    ASSET_DIR.mkdir(parents=True, exist_ok=True)
    benchmark_path = ASSET_DIR / "benchmark.svg"
    confusion_path = ASSET_DIR / "confusion.svg"
    benchmark_path.write_text(benchmark_svg, encoding="utf-8", newline="\n")
    confusion_path.write_text(confusion_svg, encoding="utf-8", newline="\n")
    recalls = ", ".join(f"{row.name} {row.recall}" for row in categories)
    print(
        f"wrote {rel(benchmark_path)}: "
        f"P {headline.precision} R {headline.recall} "
        f"F1 {headline.f1} FPR {headline.fpr}; {recalls}"
    )
    print(
        f"wrote {rel(confusion_path)}: "
        f"TP {headline.tp} FP {headline.fp} TN {headline.tn} FN {headline.fn}"
    )


if __name__ == "__main__":
    main()
